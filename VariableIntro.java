public class VariableIntro {
	public static void main(String[] args) {
		boolean booleanVariable = true;
		// Multiple declarations in one line
		int intVariable, intVariable2;
		intVariable = 5;


		// Primitive Data Types 
		// 8 bits = 1 byte 
		byte byteVariable = 127; // 8 bits
		short shortVariable = 32767; // 16 bits
		int intVariableForPri = 2147483647; // 32 bits
		long longVariable = 9223372036854775807L; // 64 bits



		// non primitive data types
		String stringVariable = "Hello World"; // String is enclosed in double quotes

		// using class
		String stringVariable2 = new String("Hello World");	// original is a class, new is a keyword

	}
}